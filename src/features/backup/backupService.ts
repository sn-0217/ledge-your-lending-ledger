import { getDb } from "@/lib/db";
import { LEDGE_COLLECTIONS } from "@/lib/db";
import { queueCloudDelete, queueCloudUpsert } from "@/features/sync/cloudSync";
import type {
  Person,
  DebtCategory,
  Transaction,
  Chitti,
  ChittiMonthlyPayment,
  Loan,
  LoanMonthlyPayment,
  RepaymentPlan,
} from "@/lib/types";

export interface BackupData {
  app: "ledge";
  version: number;
  exportedAt: string;
  people: Person[];
  categories: DebtCategory[];
  transactions: Transaction[];
  chittis: Chitti[];
  chittiPayments: ChittiMonthlyPayment[];
  repaymentPlans: RepaymentPlan[];
  loans: Loan[];
  loanPayments: LoanMonthlyPayment[];
}

export function validateAndMigrateBackup(data: unknown): BackupData {
  if (!data || typeof data !== "object" || Array.isArray(data)) {
    throw new Error("Invalid backup: data is not an object.");
  }
  const backup = data as Record<string, unknown>;

  if (backup.app !== "ledge") {
    throw new Error("Invalid backup: file was not generated by Ledge.");
  }

  const version = Number(backup.version || 1);
  if (isNaN(version)) {
    throw new Error("Invalid backup: missing database version.");
  }

  // Basic lists initialization
  const people: Person[] = Array.isArray(backup.people) ? (backup.people as Person[]) : [];
  const categories: DebtCategory[] = Array.isArray(backup.categories)
    ? (backup.categories as DebtCategory[])
    : [];
  const transactions: Transaction[] = Array.isArray(backup.transactions)
    ? (backup.transactions as Transaction[])
    : [];
  const chittis: Chitti[] = Array.isArray(backup.chittis) ? (backup.chittis as Chitti[]) : [];
  const chittiPayments: ChittiMonthlyPayment[] = Array.isArray(backup.chittiPayments)
    ? (backup.chittiPayments as ChittiMonthlyPayment[])
    : [];
  const repaymentPlans: RepaymentPlan[] = Array.isArray(backup.repaymentPlans)
    ? (backup.repaymentPlans as RepaymentPlan[])
    : [];
  const loans: Loan[] = Array.isArray(backup.loans) ? (backup.loans as Loan[]) : [];
  const loanPayments: LoanMonthlyPayment[] = Array.isArray(backup.loanPayments)
    ? (backup.loanPayments as LoanMonthlyPayment[])
    : [];

  // 1. Validate People
  for (const p of people) {
    if (!p.id || typeof p.id !== "string")
      throw new Error("Validation failed: Person missing string id.");
    if (!p.name || typeof p.name !== "string")
      throw new Error("Validation failed: Person missing name.");
    if (!Array.isArray(p.tags)) p.tags = [];
    if (!p.createdAt) p.createdAt = Date.now();
    if (!p.updatedAt) p.updatedAt = p.createdAt;
  }

  // 2. Validate Categories
  for (const c of categories) {
    if (!c.id || typeof c.id !== "string")
      throw new Error("Validation failed: Category missing string id.");
    if (!c.personId || typeof c.personId !== "string")
      throw new Error("Validation failed: Category missing personId.");
    if (!c.name || typeof c.name !== "string")
      throw new Error("Validation failed: Category missing name.");
    if (!c.createdAt) c.createdAt = Date.now();
    if (!c.updatedAt) c.updatedAt = c.createdAt;
  }

  // 3. Validate Transactions
  for (const t of transactions) {
    if (!t.id || typeof t.id !== "string")
      throw new Error("Validation failed: Transaction missing string id.");
    if (!t.personId || typeof t.personId !== "string")
      throw new Error("Validation failed: Transaction missing personId.");
    if (!t.categoryId || typeof t.categoryId !== "string")
      throw new Error("Validation failed: Transaction missing categoryId.");
    if (typeof t.amount !== "number" || isNaN(t.amount))
      throw new Error("Validation failed: Transaction amount is invalid.");
    if (!t.type || !["lent", "borrowed", "repayment_in", "repayment_out"].includes(t.type)) {
      throw new Error(`Validation failed: Transaction has invalid type "${t.type}".`);
    }
    if (!t.date) t.date = Date.now();
    if (!t.createdAt) t.createdAt = t.date;
    if (!t.updatedAt) t.updatedAt = t.createdAt;
  }

  // 4. Validate Chittis (Migrating v1 if needed)
  for (const c of chittis) {
    if (!c.id || typeof c.id !== "string")
      throw new Error("Validation failed: Chitti missing string id.");
    if (!c.organizerId || typeof c.organizerId !== "string")
      throw new Error("Validation failed: Chitti missing organizerId.");
    if (typeof c.monthlyAmount !== "number" || isNaN(c.monthlyAmount))
      throw new Error("Validation failed: Chitti monthlyAmount is invalid.");
    if (typeof c.numChits !== "number" || isNaN(c.numChits)) c.numChits = 1;
    if (!c.startDate) c.startDate = Date.now();
    if (typeof c.totalMonths !== "number" || isNaN(c.totalMonths)) c.totalMonths = 12;
    if (!c.status || !["active", "completed", "cancelled"].includes(c.status)) c.status = "active";
    if (c.availed === undefined) c.availed = false;
    if (!c.createdAt) c.createdAt = Date.now();
    if (!c.updatedAt) c.updatedAt = c.createdAt;

    // Migrate v1 legacy fields to availedSlots array if needed
    if (!c.availedSlots) {
      c.availedSlots = [
        {
          chitNumber: 1,
          availed: c.availed,
          availedDate: c.availedDate,
          availedAmount: c.availedAmount,
        },
      ];
    }
  }

  // 5. Validate Chitti Payments
  for (const cp of chittiPayments) {
    if (!cp.id || typeof cp.id !== "string")
      throw new Error("Validation failed: Chitti Payment missing string id.");
    if (!cp.chittiId || typeof cp.chittiId !== "string")
      throw new Error("Validation failed: Chitti Payment missing chittiId.");
    if (typeof cp.month !== "number" || isNaN(cp.month))
      throw new Error("Validation failed: Chitti Payment month is invalid.");
    if (typeof cp.paidAmount !== "number" || isNaN(cp.paidAmount))
      throw new Error("Validation failed: Chitti Payment paidAmount is invalid.");
    if (!cp.paidDate) cp.paidDate = Date.now();
    if (!cp.createdAt) cp.createdAt = cp.paidDate;
    if (!cp.updatedAt) cp.updatedAt = cp.createdAt;
  }

  // 6. Validate optional monthly repayment plans (absent in older backups).
  for (const plan of repaymentPlans) {
    if (!plan.id || typeof plan.id !== "string")
      throw new Error("Validation failed: Repayment plan missing string id.");
    if (!plan.personId || typeof plan.personId !== "string")
      throw new Error("Validation failed: Repayment plan missing personId.");
    if (!plan.categoryId || typeof plan.categoryId !== "string")
      throw new Error("Validation failed: Repayment plan missing categoryId.");
    if (
      typeof plan.monthlyAmount !== "number" ||
      !Number.isFinite(plan.monthlyAmount) ||
      plan.monthlyAmount <= 0
    )
      throw new Error("Validation failed: Repayment plan monthly amount is invalid.");
    if (typeof plan.firstDueDate !== "number" || !Number.isFinite(plan.firstDueDate))
      throw new Error("Validation failed: Repayment plan due date is invalid.");
    if (
      plan.totalAmount !== undefined &&
      (typeof plan.totalAmount !== "number" ||
        !Number.isFinite(plan.totalAmount) ||
        plan.totalAmount <= 0)
    )
      throw new Error("Validation failed: Repayment plan total amount is invalid.");
    if (
      plan.totalMonths !== undefined &&
      (!Number.isInteger(plan.totalMonths) || plan.totalMonths < 1 || plan.totalMonths > 600)
    )
      throw new Error("Validation failed: Repayment plan duration is invalid.");
    if (
      plan.scheduleMode !== undefined &&
      plan.scheduleMode !== "months" &&
      plan.scheduleMode !== "amount"
    )
      throw new Error("Validation failed: Repayment plan schedule mode is invalid.");
    if (!plan.createdAt) plan.createdAt = Date.now();
    if (!plan.updatedAt) plan.updatedAt = plan.createdAt;
  }

  for (const loan of loans) {
    if (!loan.id || typeof loan.id !== "string")
      throw new Error("Validation failed: Loan missing string id.");
    if (!loan.name || typeof loan.name !== "string")
      throw new Error("Validation failed: Loan missing name.");
    if (!loan.lender || typeof loan.lender !== "string")
      throw new Error("Validation failed: Loan missing lender.");
    if (!["house", "car", "personal", "other"].includes(loan.kind))
      throw new Error("Validation failed: Loan type is invalid.");
    if (
      typeof loan.principalAmount !== "number" ||
      !Number.isFinite(loan.principalAmount) ||
      loan.principalAmount <= 0
    )
      throw new Error("Validation failed: Loan amount is invalid.");
    if (
      typeof loan.monthlyAmount !== "number" ||
      !Number.isFinite(loan.monthlyAmount) ||
      loan.monthlyAmount <= 0
    )
      throw new Error("Validation failed: Loan monthly amount is invalid.");
    if (!Number.isInteger(loan.totalMonths) || loan.totalMonths < 1 || loan.totalMonths > 600)
      throw new Error("Validation failed: Loan duration is invalid.");
    if (typeof loan.startDate !== "number" || !Number.isFinite(loan.startDate))
      throw new Error("Validation failed: Loan start date is invalid.");
    if (!loan.status || !["active", "completed", "cancelled"].includes(loan.status))
      loan.status = "active";
    if (!loan.createdAt) loan.createdAt = Date.now();
    if (!loan.updatedAt) loan.updatedAt = loan.createdAt;
  }

  for (const payment of loanPayments) {
    if (!payment.id || typeof payment.id !== "string")
      throw new Error("Validation failed: Loan payment missing string id.");
    if (!payment.loanId || typeof payment.loanId !== "string")
      throw new Error("Validation failed: Loan payment missing loanId.");
    if (!Number.isInteger(payment.month) || payment.month < 1)
      throw new Error("Validation failed: Loan payment month is invalid.");
    if (
      typeof payment.paidAmount !== "number" ||
      !Number.isFinite(payment.paidAmount) ||
      payment.paidAmount <= 0
    )
      throw new Error("Validation failed: Loan payment amount is invalid.");
    if (!payment.paidDate) payment.paidDate = Date.now();
    if (!payment.createdAt) payment.createdAt = payment.paidDate;
    if (!payment.updatedAt) payment.updatedAt = payment.createdAt;
  }

  return {
    app: "ledge",
    version: 5,
    exportedAt: new Date().toISOString(),
    people,
    categories,
    transactions,
    chittis,
    chittiPayments,
    repaymentPlans,
    loans,
    loanPayments,
  };
}

export async function getDatabaseBackupPayload(): Promise<
  Omit<BackupData, "app" | "version" | "exportedAt">
> {
  const db = getDb();
  const [
    people,
    categories,
    transactions,
    chittis,
    chittiPayments,
    repaymentPlans,
    loans,
    loanPayments,
  ] = await Promise.all([
    db.people.toArray(),
    db.categories.toArray(),
    db.transactions.toArray(),
    db.chittis.toArray(),
    db.chittiPayments.toArray(),
    db.repaymentPlans.toArray(),
    db.loans.toArray(),
    db.loanPayments.toArray(),
  ]);
  return {
    people,
    categories,
    transactions,
    chittis,
    chittiPayments,
    repaymentPlans,
    loans,
    loanPayments,
  };
}

export async function importBackupPayload(payload: unknown) {
  const validated = validateAndMigrateBackup(payload);
  const db = getDb();
  const previous = await Promise.all([
    db.people.toArray(),
    db.categories.toArray(),
    db.transactions.toArray(),
    db.chittis.toArray(),
    db.chittiPayments.toArray(),
    db.repaymentPlans.toArray(),
    db.loans.toArray(),
    db.loanPayments.toArray(),
  ]);

  await db.transaction(
    "rw",
    [
      db.people,
      db.categories,
      db.transactions,
      db.chittis,
      db.chittiPayments,
      db.repaymentPlans,
      db.loans,
      db.loanPayments,
    ],
    async () => {
      // Clear current database values
      await Promise.all([
        db.people.clear(),
        db.categories.clear(),
        db.transactions.clear(),
        db.chittis.clear(),
        db.chittiPayments.clear(),
        db.repaymentPlans.clear(),
        db.loans.clear(),
        db.loanPayments.clear(),
      ]);

      // Bulk write values
      if (validated.people.length > 0) await db.people.bulkAdd(validated.people);
      if (validated.categories.length > 0) await db.categories.bulkAdd(validated.categories);
      if (validated.transactions.length > 0) await db.transactions.bulkAdd(validated.transactions);
      if (validated.chittis.length > 0) await db.chittis.bulkAdd(validated.chittis);
      if (validated.chittiPayments.length > 0)
        await db.chittiPayments.bulkAdd(validated.chittiPayments);
      if (validated.repaymentPlans.length > 0)
        await db.repaymentPlans.bulkAdd(validated.repaymentPlans);
      if (validated.loans.length > 0) await db.loans.bulkAdd(validated.loans);
      if (validated.loanPayments.length > 0) await db.loanPayments.bulkAdd(validated.loanPayments);
    },
  );

  const imported = [
    validated.people,
    validated.categories,
    validated.transactions,
    validated.chittis,
    validated.chittiPayments,
    validated.repaymentPlans,
    validated.loans,
    validated.loanPayments,
  ];
  await Promise.all(
    LEDGE_COLLECTIONS.flatMap((collection, index) => [
      ...previous[index].map((record) => queueCloudDelete(collection, record.id)),
      ...imported[index].map((record) =>
        queueCloudUpsert(collection, record as unknown as Record<string, unknown>),
      ),
    ]),
  );
}

function escapeHTML(str: string): string {
  return str.replace(/[&<>'"]/g, (tag) => {
    return (
      {
        "&": "&amp;",
        "<": "&lt;",
        ">": "&gt;",
        "'": "&#39;",
        '"': "&quot;",
      }[tag] || tag
    );
  });
}

export function downloadFile(content: BlobPart, filename: string, mimeType: string) {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  a.click();
  URL.revokeObjectURL(url);
}

export async function exportToJSON() {
  const data = await getDatabaseBackupPayload();
  const payload = {
    app: "ledge",
    version: 4,
    exportedAt: new Date().toISOString(),
    ...data,
  };
  const jsonStr = JSON.stringify(payload, null, 2);
  downloadFile(
    jsonStr,
    `ledge-backup-${new Date().toISOString().slice(0, 10)}.json`,
    "application/json",
  );
}

export async function exportToCSV() {
  const db = getDb();
  const [people, categories, transactions] = await Promise.all([
    db.people.toArray(),
    db.categories.toArray(),
    db.transactions.toArray(),
  ]);

  const peopleById = new Map(people.map((p) => [p.id, p]));
  const catsById = new Map(categories.map((c) => [c.id, c]));

  const headers = ["Date", "Person", "Category", "Type", "Amount", "Due Date", "Notes"];
  const rows = [
    headers,
    ...transactions.map((t) => [
      new Date(t.date).toISOString().slice(0, 10),
      peopleById.get(t.personId)?.name ?? "",
      catsById.get(t.categoryId)?.name ?? "",
      t.type,
      String(t.amount),
      t.dueDate ? new Date(t.dueDate).toISOString().slice(0, 10) : "",
      (t.notes ?? "").replace(/\n/g, " "),
    ]),
  ];

  const csvContent = rows
    .map((r) => r.map((cell) => `"${String(cell).replace(/"/g, '""')}"`).join(","))
    .join("\n");

  downloadFile(
    csvContent,
    `ledge-transactions-${new Date().toISOString().slice(0, 10)}.csv`,
    "text/csv",
  );
}

export async function exportToExcel() {
  const db = getDb();
  const [people, categories, transactions] = await Promise.all([
    db.people.toArray(),
    db.categories.toArray(),
    db.transactions.toArray(),
  ]);

  const peopleById = new Map(people.map((p) => [p.id, p]));
  const catsById = new Map(categories.map((c) => [c.id, c]));

  const tableRows = transactions
    .map((t) => {
      const pName = peopleById.get(t.personId)?.name ?? "";
      const cName = catsById.get(t.categoryId)?.name ?? "";
      const dateStr = new Date(t.date).toISOString().slice(0, 10);
      const dueDateStr = t.dueDate ? new Date(t.dueDate).toISOString().slice(0, 10) : "";
      const notesStr = t.notes ?? "";

      return `
      <tr>
        <td>${dateStr}</td>
        <td>${escapeHTML(pName)}</td>
        <td>${escapeHTML(cName)}</td>
        <td>${t.type}</td>
        <td style="mso-number-format:'\\#,\\#\\#0\\.00'; text-align:right;">${t.amount}</td>
        <td>${dueDateStr}</td>
        <td>${escapeHTML(notesStr)}</td>
      </tr>
    `;
    })
    .join("");

  const excelTemplate = `
    <html xmlns:o="urn:schemas-microsoft-com:office:office" xmlns:x="urn:schemas-microsoft-com:office:excel" xmlns="http://www.w3.org/TR/REC-html40">
    <head>
      <!--[if gte mso 9]>
      <xml>
        <x:ExcelWorkbook>
          <x:ExcelWorksheets>
            <x:ExcelWorksheet>
              <x:Name>Transactions</x:Name>
              <x:WorksheetOptions>
                <x:DisplayGridlines/>
              </x:WorksheetOptions>
            </x:ExcelWorksheet>
          </x:ExcelWorksheets>
        </x:ExcelWorkbook>
      </xml>
      <![endif]-->
      <style>
        th { background-color: #f2f2f2; font-weight: bold; border: 1px solid #cccccc; }
        td { border: 1px solid #cccccc; }
        table { border-collapse: collapse; }
      </style>
    </head>
    <body>
      <table>
        <thead>
          <tr>
            <th>Date</th>
            <th>Person</th>
            <th>Category</th>
            <th>Type</th>
            <th>Amount</th>
            <th>Due Date</th>
            <th>Notes</th>
          </tr>
        </thead>
        <tbody>
          ${tableRows}
        </tbody>
      </table>
    </body>
    </html>
  `;

  downloadFile(
    excelTemplate,
    `ledge-transactions-${new Date().toISOString().slice(0, 10)}.xls`,
    "application/vnd.ms-excel",
  );
}
